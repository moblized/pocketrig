"""Writes PocketRig's original launcher, notification and logo vectors (a handheld with a download arrow)."""
import os, sys
res = sys.argv[1]

BODY = "M35,37H73A13,13 0 0 1 86,50V58A13,13 0 0 1 73,71H35A13,13 0 0 1 22,58V50A13,13 0 0 1 35,37Z"
SCREEN = "M42,42H66A3,3 0 0 1 69,45V63A3,3 0 0 1 66,66H42A3,3 0 0 1 39,63V45A3,3 0 0 1 42,42Z"
DPAD = "M28.5,48H32.5V52H36.5V56H32.5V60H28.5V56H24.5V52H28.5Z"
BTN_A = "M72.4,57a2.6,2.6 0 1 0 5.2,0a2.6,2.6 0 1 0 -5.2,0Z"
BTN_B = "M77.4,51a2.6,2.6 0 1 0 5.2,0a2.6,2.6 0 1 0 -5.2,0Z"
ARROW = "M52,46H56V53H60.5L54,59.5L47.5,53H52Z M47,61.5H61V63.5H47Z"

INDIGO, CYAN, NIGHT, INK = "#FF6366F1", "#FF06B6D4", "#FF0B1020", "#FF1E1B4B"

def grad(x0, y0, x1, y1, a, b):
    return f'''
        <aapt:attr name="android:fillColor">
            <gradient android:type="linear" android:startX="{x0}" android:startY="{y0}" android:endX="{x1}" android:endY="{y1}">
                <item android:offset="0" android:color="{a}"/>
                <item android:offset="1" android:color="{b}"/>
            </gradient>
        </aapt:attr>'''

def path(d, fill=None, gradient=None, even_odd=False):
    attrs = f'android:pathData="{d}"'
    if even_odd:
        attrs += ' android:fillType="evenOdd"'
    if gradient:
        return f'    <path {attrs}>{gradient}\n    </path>\n'
    return f'    <path {attrs} android:fillColor="{fill}"/>\n'

def vector(body, w=108, h=108, vw=108, vh=108, aapt=False, group=None):
    ns = ' xmlns:aapt="http://schemas.android.com/aapt"' if aapt else ''
    if group:
        body = f'  <group {group}>\n{body}  </group>\n'
    return (f'<?xml version="1.0" encoding="utf-8"?>\n<!-- PocketRig icon (original artwork). Generated by tools/make_icons.py -->\n'
            f'<vector xmlns:android="http://schemas.android.com/apk/res/android"{ns}\n'
            f'    android:width="{w}dp" android:height="{h}dp"\n'
            f'    android:viewportWidth="{vw}" android:viewportHeight="{vh}">\n{body}</vector>\n')

def write(rel, text):
    p = os.path.join(res, rel)
    os.makedirs(os.path.dirname(p), exist_ok=True)
    open(p, "w").write(text)

# Light: colourful background, white handheld.
write("drawable/pr_icon_bg_light.xml", vector(path("M0,0h108v108h-108z", gradient=grad(0, 0, 108, 108, INDIGO, CYAN)), aapt=True))
write("drawable/pr_icon_fg_light.xml", vector(
    path(BODY, "#FFFFFFFF") + path(SCREEN, INK) + path(ARROW, "#FF22D3EE") +
    path(DPAD, INK) + path(BTN_A, INDIGO) + path(BTN_B, CYAN)))
# Dark: near-black background, colourful handheld.
write("drawable/pr_icon_bg_dark.xml", vector(path("M0,0h108v108h-108z", gradient=grad(0, 0, 108, 108, "#FF0B1020", "#FF151B2E")), aapt=True))
fg_dark = (path(BODY, gradient=grad(22, 37, 86, 71, INDIGO, CYAN)) + path(SCREEN, NIGHT) +
           path(ARROW, "#FF22D3EE") + path(DPAD, NIGHT) + path(BTN_A, NIGHT) + path(BTN_B, NIGHT))
write("drawable/pr_icon_fg_dark.xml", vector(fg_dark, aapt=True))
# Monochrome (Android 13+ themed icons) and notification glyph: one colour, screen and controls cut out.
cutout = path(" ".join([BODY, SCREEN, DPAD, BTN_A, BTN_B]), "#FFFFFFFF", even_odd=True) + path(ARROW, "#FFFFFFFF")
write("drawable/pr_icon_mono.xml", vector(cutout))
for name in ("ic_notification", "ic_notification_alt"):
    write(f"drawable-anydpi/{name}.xml", vector(cutout, w=24, h=24, vw=24, vh=24,
          group='android:scaleX="0.34" android:scaleY="0.34" android:translateX="-6.48" android:translateY="-6.36"'))
# In-app logo (splash, placeholders): the colourful handheld, cropped to the device.
write("drawable/ic_logo_color.xml", vector(fg_dark, w=1000, h=1000, vw=72, vh=72, aapt=True,
      group='android:translateX="-18" android:translateY="-18"'))

# Theme-following aliases: day = light icon, night = dark icon.
for folder, kind in (("values", "light"), ("values-night", "dark")):
    write(f"{folder}/pr_icons.xml", f'''<?xml version="1.0" encoding="utf-8"?>
<!-- The default launcher icon follows the system: light by day, dark in dark mode. -->
<resources>
    <item name="pr_icon_bg" type="drawable">@drawable/pr_icon_bg_{kind}</item>
    <item name="pr_icon_fg" type="drawable">@drawable/pr_icon_fg_{kind}</item>
</resources>
''')

def adaptive(bg, fg):
    return f'''<?xml version="1.0" encoding="utf-8"?>
<adaptive-icon xmlns:android="http://schemas.android.com/apk/res/android">
    <background android:drawable="@drawable/{bg}"/>
    <foreground android:drawable="@drawable/{fg}"/>
    <monochrome android:drawable="@drawable/pr_icon_mono"/>
</adaptive-icon>
'''
for name, bg, fg in (("ic_launcher", "pr_icon_bg", "pr_icon_fg"),          # follows system (theme: System Default)
                     ("ic_launcher_light", "pr_icon_bg_light", "pr_icon_fg_light"),  # theme: Light
                     ("ic_launcher_alt", "pr_icon_bg_dark", "pr_icon_fg_dark")):     # theme: Dark / AMOLED
    write(f"mipmap-anydpi-v26/{name}.xml", adaptive(bg, fg))
    write(f"mipmap-anydpi-v26/{name}_round.xml", adaptive(bg, fg))
print("icons written")
